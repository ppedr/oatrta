def git(repo: Path, *args: str) -> str:
    r = subprocess.run(["git", "-C", str(repo), "-c", "user.name=oatrta-eval", "-c", "user.email=eval@example.com",
                        *args], check=True, capture_output=True, text=True)
    return r.stdout.strip()


def main(argv: list[str]) -> int:
    args = [a for a in argv if not a.startswith("--")]
    if len(args) != 1:
        print(__doc__, file=sys.stderr)
        return 2
    dest = Path(args[0]).resolve()
    if dest.exists() and any(dest.iterdir()):
        print(f"refusing to write into a non-empty directory: {dest}", file=sys.stderr)
        return 2
    files = dict(FILES)
    if "--without-agents-md" not in argv:
        files["AGENTS.md"] = AGENTS_MD
    for rel, text in files.items():
        p = dest / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(text.encode("utf-8"))  # exact LF on every OS
    git(dest, "init", "-q")
    git(dest, "config", "core.autocrlf", "false")
    git(dest, "add", ".")
    git(dest, "commit", "-qm", "sample repository")
    base = git(dest, "rev-parse", "HEAD")
    (dest / ".git" / "oatrta-sample-base").write_text(base + "\n", encoding="utf-8")
    print(f"sample repository at {dest} (commit {base[:8]})")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
